#!/usr/bin/env node
/**
 * Generates src/app/studio/legacy-theme.css: re-skins every existing BlinkSpot component when it
 * renders inside the new /studio UI, WITHOUT editing those components (the classic /dashboard
 * design stays exactly as it is). It finds every Tailwind class with a hard-coded legacy colour,
 * e.g. `hover:bg-[#C5BAC4]/80`, and maps the colour to a new design token, scoped to `.studio`.
 *   node scripts/ui/gen-studio-theme.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = new URL("../../src/", import.meta.url).pathname;
// legacy hex -> new token (see src/app/studio/studio.css)
const MAP = {
  "#191D23": "--s-bg", "#0F1115": "--s-bg", "#0E1117": "--s-bg", "#0A0A0A": "--s-bg", "#000000": "--s-black",
  "#1D2229": "--s-panel", "#20252C": "--s-panel", "#232830": "--s-panel", "#2A2F38": "--s-panel",
  "#3A4048": "--s-raised", "#57707A": "--s-line", "#7B919C": "--s-soft",
  "#DEDCDC": "--s-text", "#989DAA": "--s-soft", "#9B8EA8": "--s-soft",
  "#C5BAC4": "--s-accent", "#B3FF00": "--s-accent", "#D0FF69": "--s-accent",
  "#00E5FF": "--s-ai", "#00B3CC": "--s-ai", "#0099B3": "--s-ai", "#B488D4": "--s-ai", "#F472B6": "--s-ai", "#60A5FA": "--s-ai",
  "#FFB300": "--s-warn", "#FB923C": "--s-warn",
};
// Same hex, different job: lilac was the button colour AND the icon/label tint, slate was the
// selected background AND the muted text. Only a solid lilac background (a primary button) becomes
// the new accent; everything else goes quiet, so one action per screen stays the loud thing.
const BY_PROP = {
  "#C5BAC4": { text: "--s-text", border: "--s-line-2", bgAlpha: "--s-text", fill: "--s-text", stroke: "--s-text" },
  "#57707A": { bg: "--s-hover", text: "--s-mute", border: "--s-line-2", fill: "--s-mute", stroke: "--s-mute" },
  "#2A2F38": { border: "--s-line" },
  "#191D23": { text: "--s-accent-ink", border: "--s-line" },
  "#000000": { text: "--s-black" },
};
// where a legacy colour was used as a BACKGROUND for primary buttons, the label must flip to dark
const PROPS = {
  bg: (v) => `background-color:${v}`, text: (v) => `color:${v}`, border: (v) => `border-color:${v}`,
  from: (v) => `--tw-gradient-from:${v}`, via: (v) => `--tw-gradient-via:${v}`, to: (v) => `--tw-gradient-to:${v}`,
  ring: (v) => `--tw-ring-color:${v}`, shadow: (v) => `--tw-shadow-color:${v}`, fill: (v) => `fill:${v}`, stroke: (v) => `stroke:${v}`,
  accent: (v) => `accent-color:${v}`, outline: (v) => `outline-color:${v}`, caret: (v) => `caret-color:${v}`, decoration: (v) => `text-decoration-color:${v}`,
};
const VARIANTS = { hover: ":hover", focus: ":focus", "focus-visible": ":focus-visible", active: ":active", disabled: ":disabled", "group-hover": "GROUP", placeholder: "::placeholder" };

const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) { if (!/__tests__|studio/.test(p)) walk(p); } else if (/\.(tsx?|jsx?)$/.test(f)) files.push(p); } };
walk(ROOT);

const re = /((?:[a-z-]+:)*)(bg|text|border|from|via|to|ring|shadow|fill|stroke|accent|outline|caret|decoration)-\[(#[0-9A-Fa-f]{6})\](?:\/(\d{1,3}))?/g;
const found = new Set();
for (const f of files) for (const m of fs.readFileSync(f, "utf8").matchAll(re)) found.add(m[0]);

const esc = (s) => s.replace(/([:\[\]#\/.%])/g, "\\$1");
const rules = []; const unmapped = new Set();
for (const cls of [...found].sort()) {
  const m = cls.match(/^((?:[a-z-]+:)*)([a-z]+)-\[(#[0-9A-Fa-f]{6})\](?:\/(\d{1,3}))?$/);
  if (!m) continue;
  const [, variantStr, prop, hexRaw, alpha] = m;
  const hex = hexRaw.toUpperCase();
  const over = BY_PROP[hex] || {};
  const token = (prop === "bg" && alpha && over.bgAlpha) || over[prop] || MAP[hex];
  if (!token) { unmapped.add(hex); continue; }
  const value = alpha ? `color-mix(in oklab, var(${token}) ${alpha}%, transparent)` : `var(${token})`;
  const variants = variantStr ? variantStr.slice(0, -1).split(":") : [];
  let pseudo = "", group = false, skip = false;
  for (const v of variants) {
    if (VARIANTS[v] === "GROUP") group = true;
    else if (VARIANTS[v]) pseudo += VARIANTS[v];
    else if (!/^(sm|md|lg|xl|2xl|dark|data-\[.*\]|aria-\[.*\]|peer-.*)$/.test(v)) skip = true; // responsive etc. apply as base
  }
  if (skip) continue;
  const sel = `${group ? ".studio .group:hover " : ".studio "}.${esc(cls)}${pseudo}`;
  rules.push(`${sel}{${PROPS[prop](value)}}`);
  // a legacy primary button (lilac/lime background) gets the dark label the new accent needs
  if (prop === "bg" && token === "--s-accent" && !alpha && !group) rules.push(`${sel}{color:var(--s-accent-ink)}`);
}
const out = `/* GENERATED by scripts/ui/gen-studio-theme.mjs. Do not edit; re-run the script. */\n/* ${found.size} legacy colour classes found, ${rules.length} rules. */\n${rules.join("\n")}\n`;
fs.mkdirSync(path.join(ROOT, "app/studio"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "app/studio/legacy-theme.css"), out);
console.log(`${found.size} classes, ${rules.length} rules${unmapped.size ? `, unmapped: ${[...unmapped].join(" ")}` : ""}`);
